const canvas = document.querySelector("#networkCanvas");
const context = canvas.getContext("2d");
const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
let points = [];
let width = 0;
let height = 0;

function resizeCanvas() {
  const scale = Math.min(window.devicePixelRatio || 1, 1.75);
  width = window.innerWidth;
  height = window.innerHeight;
  canvas.width = Math.floor(width * scale);
  canvas.height = Math.floor(height * scale);
  canvas.style.width = `${width}px`;
  canvas.style.height = `${height}px`;
  context.setTransform(scale, 0, 0, scale, 0, 0);
  const count = Math.max(36, Math.min(86, Math.floor(width / 18)));
  points = Array.from({ length: count }, (_, index) => ({
    x: (index * 97) % width,
    y: (index * 53) % height,
    vx: (index % 5 - 2) * 0.12,
    vy: ((index + 2) % 5 - 2) * 0.1,
    color: index % 3 === 0 ? "#43d98d" : index % 3 === 1 ? "#66d9ef" : "#f1c96b"
  }));
}

function drawNetwork() {
  context.clearRect(0, 0, width, height);
  context.lineWidth = 1;
  for (let i = 0; i < points.length; i += 1) {
    const a = points[i];
    if (!reducedMotion) {
      a.x += a.vx;
      a.y += a.vy;
      if (a.x < -20) a.x = width + 20;
      if (a.x > width + 20) a.x = -20;
      if (a.y < -20) a.y = height + 20;
      if (a.y > height + 20) a.y = -20;
    }
    context.fillStyle = a.color;
    context.globalAlpha = 0.48;
    context.beginPath();
    context.arc(a.x, a.y, 2, 0, Math.PI * 2);
    context.fill();
    for (let j = i + 1; j < points.length; j += 1) {
      const b = points[j];
      const dx = a.x - b.x;
      const dy = a.y - b.y;
      const distance = Math.sqrt(dx * dx + dy * dy);
      if (distance < 132) {
        context.strokeStyle = a.color;
        context.globalAlpha = (1 - distance / 132) * 0.16;
        context.beginPath();
        context.moveTo(a.x, a.y);
        context.lineTo(b.x, b.y);
        context.stroke();
      }
    }
  }
  context.globalAlpha = 1;
  if (!reducedMotion) {
    requestAnimationFrame(drawNetwork);
  }
}

function setLanguage(language) {
  const selected = translations[language] ? language : "zh";
  document.documentElement.lang = selected === "zh" ? "zh-CN" : "en";
  for (const element of document.querySelectorAll("[data-i18n]")) {
    const key = element.getAttribute("data-i18n");
    if (translations[selected][key]) {
      element.textContent = translations[selected][key];
    }
  }
  const label = document.querySelector("#langLabel");
  if (label) {
    label.textContent = selected === "zh" ? "EN" : "中";
  }
  localStorage.setItem("huntercore-site-lang", selected);
  if (window.lucide) {
    window.lucide.createIcons();
  }
}

window.addEventListener("resize", resizeCanvas);
resizeCanvas();
drawNetwork();

document.querySelector("#langToggle")?.addEventListener("click", () => {
  const next = document.documentElement.lang.startsWith("zh") ? "en" : "zh";
  setLanguage(next);
});

setLanguage(localStorage.getItem("huntercore-site-lang") || "zh");
